
# Day 02 - Python Operators

# 1. Arithmetic operators
a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

# 2. Comparison operators
print("Is a greater than b?", a > b)
print("Are they equal?", a == b)
print("Are they different?", a != b)

# 3. Logical operators
age = 20
has_id = True

print("Can enter:", age >= 18 and has_id)
print("Under 18 or has ID:", age < 18 or has_id)
print("Does not have ID:", not has_id)

# 4. Assignment operators
score = 10
score += 5
print("Updated score:", score)

